"""Build comparison/matrix.md from the source-reviewed records in data/*.json.

Usage: python scripts/build_matrix.py
"""

import json
import pathlib
import argparse

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "comparison" / "matrix.md"

CATEGORY_ORDER = ["llm-library", "harness-library", "hybrid", "agent-framework", "integrated-product", "execution-runtime"]
SCORE_KEYS = [
    ("flexibility", "Flex"),
    ("integration", "Integ"),
    ("embeddability", "Embed"),
    ("durability", "Durab"),
    ("safety", "Safety"),
    ("extensibility", "Ext"),
    ("multi_agent", "Multi"),
    ("provider_neutrality", "Prov"),
    ("maturity", "Matur"),
    ("minimalism", "Mini"),
]
FEATURE_KEYS = [
    ("mcp_client", "MCP client"),
    ("mcp_server", "MCP server"),
    ("skills", "Skills"),
    ("hooks", "Hooks"),
    ("plugins", "Plugins"),
    ("subagents", "Subagents"),
    ("acp", "ACP"),
    ("headless", "Headless"),
    ("in_process_sdk", "In-proc SDK"),
    ("http_server", "HTTP server"),
    ("durable_resume", "Durable/resume"),
    ("compaction", "Compaction"),
    ("os_sandbox", "OS sandbox"),
    ("approvals", "Approvals"),
    ("plan_mode", "Plan mode"),
    ("worktrees", "Worktrees"),
    ("otel", "OTel"),
    ("web_ui", "Web UI"),
    ("ide", "IDE"),
    ("agents_md", "AGENTS.md-style"),
]
MARK = {"yes": "●", "partial": "◐", "no": "·", "unknown": "?"}
DIM_KEYS = [
    ("loop", "Agent loop"),
    ("providers", "Providers"),
    ("tools", "Tools"),
    ("context", "Context management"),
    ("state", "State & durability"),
    ("safety", "Safety"),
    ("extensibility", "Extensibility"),
    ("multi_agent", "Multi-agent"),
    ("surfaces", "Surfaces"),
    ("observability", "Observability"),
]


def esc(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


def load_records():
    records = []
    for path in sorted(DATA.glob("*.json")):
        payload = json.loads(path.read_text(encoding="utf-8-sig"))
        for rec in payload.get("records", []):
            rec["_file"] = path.name
            records.append(rec)
    seen = {}
    for rec in records:
        if rec["slug"] in seen:
            raise ValueError(f"Duplicate record slug: {rec['slug']}")
        seen[rec["slug"]] = rec
    records = list(seen.values())
    records.sort(key=lambda r: (CATEGORY_ORDER.index(r["category"]) if r["category"] in CATEGORY_ORDER else 99, r["name"].lower()))
    return records


def link(rec):
    return f"[{esc(rec['name'])}](../{rec['doc_path']})"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated matrix is stale")
    args = parser.parse_args()
    records = load_records()
    if not records:
        raise ValueError("No comparison records found in data/*.json")
    lines = [
        "# Comparison matrix",
        "",
        f"Generated by `scripts/build_matrix.py` from {len(records)} source-reviewed records in `data/*.json`. Do not edit by hand.",
        "Scores use the 1–5 rubric in [`METHODOLOGY.md`](../METHODOLOGY.md). Features: ● yes · ◐ partial/optional · · no · ? unknown. A feature indicates an available capability, not a safe default or a guarantee. Read the chapter for scope and limitations.",
        "The inventory includes explicitly marked source-available and historical exceptions; it is not a list of equally open or equally mature libraries.",
        "",
        "## Identity",
        "",
        "| Harness | Category | Vendor | Language | License | Version at pin |",
        "|---|---|---|---|---|---|",
    ]
    for r in records:
        lines.append(f"| {link(r)} | `{r['category']}` | {esc(r['vendor'])} | {esc(r['language'])} | {esc(r['license'])} | {esc(r['version'])} |")

    lines += ["", "## Scorecard", "", "| Harness | " + " | ".join(h for _, h in SCORE_KEYS) + " |", "|---|" + "---:|" * len(SCORE_KEYS)]
    for r in records:
        vals = [r["scores"][k] for k, _ in SCORE_KEYS]
        lines.append(f"| {link(r)} | " + " | ".join("?" if v is None else str(v) for v in vals) + " |")
    lines += [
        "",
        "Flex = flexibility; Integ = integration; Embed = embeddability; Durab = durability; Ext = extensibility; Multi = multi-agent; Prov = provider neutrality; Matur = maturity; Mini = minimalism. Unknown scores are `?`. There is no overall winner or sum: these dimensions trade off and require use-case weights. See [`recommendations.md`](recommendations.md).",
        "",
        "## Feature matrix",
        "",
    ]
    for title, group in [("Extension and host surfaces", FEATURE_KEYS[:10]), ("Execution and product features", FEATURE_KEYS[10:])]:
        lines += [f"### {title}", "", "| Harness | " + " | ".join(h for _, h in group) + " |", "|---|" + ":---:|" * len(group)]
        for r in records:
            lines.append(f"| {link(r)} | " + " | ".join(MARK[r["features"][k]] for k, _ in group) + " |")
        lines.append("")
    lines += ["### Scope qualifications", "", "`Durable/resume` combines several mechanisms for discovery only; use the state summaries and [durability analysis](durability.md) to distinguish saved history, recovery and replay. Optional sandboxes are marked partial where backend or host selection determines isolation.", ""]
    for r in records:
        notes = r.get("features_notes", {})
        if notes:
            detail = "; ".join(f"{k}: {v}" for k, v in notes.items()) if isinstance(notes, dict) else str(notes)
            lines.append(f"- **{link(r)}**: {esc(detail)}")

    lines += ["", "## Dependency & lineage edges", "", "| Harness | Builds on | Used by |", "|---|---|---|"]
    for r in records:
        lines.append(f"| {link(r)} | {esc('; '.join(r.get('builds_on', [])) or '—')} | {esc('; '.join(r.get('used_by', [])) or '—')} |")

    lines += ["", "## One-liners", ""]
    for r in records:
        lines.append(f"- **{link(r)}**: {esc(r['one_liner'])}")

    lines += ["", "## Per-dimension summaries", ""]
    for key, title in DIM_KEYS:
        lines += [f"### {title}", "", "| Harness | Summary |", "|---|---|"]
        for r in records:
            lines.append(f"| {link(r)} | {esc(r['dims'].get(key, ''))} |")
        lines.append("")

    rendered = "\n".join(lines).rstrip() + "\n"
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != rendered:
            raise SystemExit("comparison/matrix.md is stale; run python scripts/build_matrix.py")
        print(f"matrix is current ({len(records)} records)")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT} ({len(records)} records)")


if __name__ == "__main__":
    main()
